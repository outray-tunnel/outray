import { jwt, magicLink } from "better-auth/plugins";
import { mcp } from "@better-auth/mcp";
import { cimd } from "@better-auth/cimd";
import { fetchClientMetadataResource } from "@better-auth/cimd/node";
import { APIError, createAuthMiddleware } from "better-auth/api";
import { and, eq, isNull } from "drizzle-orm";
import { db } from "../../db";
import { mcpConnections } from "../../db/mcp-schema";
import { sendViaZepto } from "../send-email";
import { MCP_CONNECTION_CLAIM, resourceFor, scopesFor } from "./config";
import { MCP_SCOPES } from "./policy";
import { hashMcpOAuthToken } from "./oauth-token-hash";
import { revokeMcpConnection } from "./connections";
import { oauthRefreshTokens } from "../../db/oauth-schema";

export function outrayMcpAuthPlugins() {
  return [
    jwt({ schema: { jwks: { modelName: "jwk" } } }),
    mcp({
      loginPage: "/plugins/sign-in", consentPage: "/plugins/authorize",
      resource: resourceFor("openai"), scopes: [...MCP_SCOPES],
      grantTypes: ["authorization_code", "refresh_token"],
      // Connection revocation must also invalidate retried rotated refresh tokens.
      refreshTokenReuseInterval: 0,
      storeTokens: { hash: hashMcpOAuthToken },
      resources: (["direct", "openai"] as const).map((catalog) => ({
        identifier: resourceFor(catalog), name: `OutRay ${catalog}`, allowedScopes: scopesFor(catalog),
      })),
      clientRegistrationDefaultResources: [resourceFor("direct"), resourceFor("openai")],
      // CIMD handles OpenAI clients. DCR remains available for standard MCP clients.
      allowDynamicClientRegistration: true, allowUnauthenticatedClientRegistration: true,
      clientRegistrationDefaultApplicationType: "infer",
      clientPrivileges: () => false,
      extensions: [{ claims: { accessToken: async ({ user, client, resources }) => {
        const uniqueResources = [...new Set(resources ?? [])];
        if (!user || uniqueResources.length !== 1) throw new APIError("FORBIDDEN", { message: "Select one OutRay MCP resource" });
        const [connection] = await db.select().from(mcpConnections).where(and(
          eq(mcpConnections.userId, user.id), eq(mcpConnections.clientId, client.clientId),
          eq(mcpConnections.resource, uniqueResources[0]), isNull(mcpConnections.revokedAt),
        )).limit(1);
        if (!connection) throw new APIError("FORBIDDEN", { message: "Connect your OutRay organizations first" });
        return { [MCP_CONNECTION_CLAIM]: { id: connection.id, generation: connection.generation } };
      } } }],
    }),
    cimd({ fetchClientMetadataResource, metadataProfile: "mcp-2026-07-28" }),
    {
      id: "outray-mcp-revocation",
      hooks: { after: [{ matcher: (context: { path?: string }) => context.path === "/oauth2/revoke",
        handler: createAuthMiddleware(async (context) => {
          // The provider authenticates the client and handles RFC 7009 first.
          // Also invalidate our JWT generation: a refresh-token revocation must
          // not leave already issued self-contained access tokens usable.
          const returned = context.context.returned;
          if (returned instanceof APIError || (returned instanceof Response && !returned.ok)) return;
          const token = context.body?.token;
          let clientId = context.body?.client_id;
          const basic = context.headers?.get("authorization")?.match(/^Basic\s+(\S+)$/i)?.[1];
          if (!clientId && basic) clientId = decodeURIComponent(Buffer.from(basic, "base64").toString().split(":")[0]);
          if (typeof token !== "string" || typeof clientId !== "string") return;
          const [refresh] = await db.select().from(oauthRefreshTokens).where(and(
            eq(oauthRefreshTokens.token, hashMcpOAuthToken(token)), eq(oauthRefreshTokens.clientId, clientId),
          )).limit(1);
          if (!refresh?.userId || !refresh.revoked) return;
          const connections = await db.select().from(mcpConnections).where(and(
            eq(mcpConnections.userId, refresh.userId), eq(mcpConnections.clientId, clientId), isNull(mcpConnections.revokedAt),
          ));
          for (const connection of connections) if (refresh.resources?.includes(connection.resource)) await revokeMcpConnection(refresh.userId, connection.id);
        }),
      }] },
    },
    magicLink({
      expiresIn: 600,
      sendMagicLink: async ({ email, url }) => {
        // The URL is generated by Better Auth and never included in application logs.
        try {
          await sendViaZepto({ recipientEmail: email, subject: "Sign in to OutRay",
            htmlString: `<p>Use this link to sign in to OutRay. It expires in 10 minutes.</p><p><a href="${url.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;")}">Sign in to OutRay</a></p><p>If you did not request this, you can ignore this email.</p>` });
        } catch { throw new APIError("SERVICE_UNAVAILABLE", { message: "Sign-in email could not be delivered" }); }
      },
    }),
  ];
}
