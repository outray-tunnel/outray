// Regenerate only the additive OAuth/JWKS tables; never overwrite auth-schema.ts.
import { writeFile } from "node:fs/promises";
import { mcp } from "@better-auth/mcp";
import { jwt } from "better-auth/plugins";

const schemas = {
  ...jwt({ schema: { jwks: { modelName: "jwk" } } }).schema,
  ...mcp({ loginPage: "/login", consentPage: "/plugins/authorize", resource: "https://outray.co/api/mcp" }).schema,
};
const snake = (value) => value.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const names = Object.fromEntries(Object.entries(schemas).map(([key, value]) => [key, `${value.modelName ?? key}s`]));
const referenced = { user: "users", session: "sessions", ...names };
let output = '// Generated by scripts/generate-mcp-auth-schema.mjs from the installed Better Auth plugins.\n';
output += 'import { pgTable, text, timestamp, boolean, integer, jsonb, index, uniqueIndex } from "drizzle-orm/pg-core";\n';
output += 'import { users, sessions } from "./auth-schema";\n\n';
for (const [model, schema] of Object.entries(schemas)) {
  const variable = names[model];
  const table = model === "jwks" ? "oauth_jwks" : snake(variable);
  output += `export const ${variable} = pgTable(${JSON.stringify(table)}, {\n  id: text("id").primaryKey(),\n`;
  for (const [field, definition] of Object.entries(schema.fields)) {
    const column = JSON.stringify(snake(field));
    let expression;
    switch (definition.type) {
      case "string": expression = `text(${column})`; break;
      case "string[]": expression = `text(${column}).array()`; break;
      case "number": expression = `integer(${column})`; break;
      case "boolean": expression = `boolean(${column})`; break;
      case "date": expression = `timestamp(${column}, { withTimezone: true })`; break;
      case "json": expression = `jsonb(${column})`; break;
      default: throw new Error(`Unsupported OAuth field type ${definition.type}`);
    }
    if (definition.required !== false) expression += '.notNull()';
    if (definition.unique) expression += '.unique()';
    if (definition.defaultValue !== undefined && typeof definition.defaultValue !== "function") expression += `.default(${JSON.stringify(definition.defaultValue)})`;
    if (definition.references) {
      const reference = definition.references;
      if (!referenced[reference.model]) throw new Error(`Unknown model ${reference.model}`);
      expression += `.references(() => ${referenced[reference.model]}.${reference.field}, { onDelete: ${JSON.stringify(reference.onDelete ?? "cascade")} })`;
    }
    output += `  ${field}: ${expression},\n`;
  }
  const indexes = Object.entries(schema.fields).filter(([, f]) => f.index).map(([field]) => `index("${table}_${snake(field)}_idx").on(t.${field})`);
  for (const idx of schema.indexes ?? []) indexes.push(`${idx.unique ? "uniqueIndex" : "index"}("${table}_${idx.fields.map(snake).join("_")}_idx").on(${idx.fields.map((field) => `t.${field}`).join(", ")})`);
  output += indexes.length ? `}, (t) => [${indexes.join(", ")}]);\n\n` : '});\n\n';
}
await writeFile(new URL('../apps/web/src/db/oauth-schema.ts', import.meta.url), output);
